package Lista8_for;

public class Ex6 {
    public static void main(String[] args) {
        int cont,soma=0;
        System.out.println("A soma dos numeros de 1 a 10 é");
        for (cont = 1;cont<=10;cont++){
            soma = cont + soma;
            System.out.println(soma);
        }


    }
}
