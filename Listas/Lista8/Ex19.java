public class Ex19 {
    public static void main(String[] args) {
        int cont;
        System.out.println("Contagem regressiva de 10 ate 0");
        for (cont = 10;cont>=0;cont--){
            System.out.println(cont);
        }
        System.out.println("Lançamento autorizado");

    }
}
